'''agents/graph.py
This module defines the shared FraudState model and the LangGraph pipeline used for fraud triage.
It provides a ``run_graph`` function that executes the sequence of agent nodes.
'''

from __future__ import annotations

from datetime import datetime
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, validator

from langgraph.graph import StateGraph, START

# Agent implementations imported inside _build_graph() to prevent circular dependency


class FraudState(BaseModel):
    """Pydantic model representing the mutable state of a fraud investigation.

    All agents receive the same instance and may read/write fields. Using a strict model
    ensures type safety and makes the graph serialisable for debugging.
    """

    # Core transaction identifiers
    transaction_id: str = Field(..., description="Unique identifier for the transaction")
    user_id: Optional[str] = Field(None, description="Optional user identifier")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="When the transaction occurred")

    # Raw input features
    amount: float = Field(..., ge=0, description="Transaction amount in USD")
    currency: str = Field(default="USD", description="Currency code")
    device_id: Optional[str] = Field(None, description="Device identifier used for the request")
    ip_address: Optional[str] = Field(None, description="IP address of the requestor")
    merchant_id: Optional[str] = Field(None, description="Identifier of the merchant/payee")

    # Intermediate calculations – populated by agents
    risk_score: Optional[float] = Field(None, ge=0, le=1, description="Aggregated risk score (0‑1)")
    risk_factors: Dict[str, Any] = Field(default_factory=dict, description="Breakdown of individual risk contributions")
    ml_prediction: Optional[float] = Field(None, description="Raw ML model prediction (probability of fraud)")
    rule_hits: List[str] = Field(default_factory=list, description="Names of rule‑based checks that fired")
    investigation_note: Optional[str] = Field(None, description="Narrative investigation note generated by LLM")
    fraud_flag: Optional[bool] = Field(None, description="Final fraud flag")
    decision_reason: Optional[str] = Field(None, description="Human readable explanation for the decision")
    audit_log: List[str] = Field(default_factory=list, description="Chronological log of state mutations")

    @validator("ip_address")
    def _validate_ip(cls, v: Optional[str]) -> Optional[str]:
        if v is None:
            return v
        parts = v.split('.')
        if len(parts) != 4 or not all(p.isdigit() and 0 <= int(p) <= 255 for p in parts):
            raise ValueError("Invalid IPv4 address")
        return v

    def log(self, message: str) -> None:
        """Append a timestamped message to the audit log."""
        self.audit_log.append(f"{datetime.utcnow().isoformat()} - {message}")

    class Config:
        orm_mode = True
        allow_mutation = True
        arbitrary_types_allowed = True


class Graph:
    def __init__(self):
        self.builder = StateGraph(FraudState)
        self.entry_point = None

    def add_node(self, name: str, action: any):
        self.builder.add_node(name, action)

    def add_edge(self, start: str, end: str):
        self.builder.add_edge(start, end)

    def set_entry_point(self, name: str):
        self.entry_point = name

    def run(self, state: FraudState) -> FraudState:
        if not hasattr(self, "_compiled_graph"):
            if self.entry_point:
                self.builder.add_edge(START, self.entry_point)
            self._compiled_graph = self.builder.compile()
        result = self._compiled_graph.invoke(state)
        return FraudState(**result)


def _build_graph() -> Graph:
    """Create a linear LangGraph pipeline.

    The flow is:
    context_gatherer -> velocity_sequence -> investigator_nlm -> decision_triage
    Each node receives a ``FraudState`` and returns the mutated ``FraudState``.
    """
    from fraud_detection.agents.context_gatherer import context_gatherer
    from fraud_detection.agents.web_data_fetcher import web_data_fetcher
    from fraud_detection.agents.velocity_sequence import velocity_sequence
    from fraud_detection.agents.investigator_nlm import investigator_nlm
    from fraud_detection.agents.decision_triage import decision_triage

    graph = Graph()
    graph.add_node("context_gatherer", context_gatherer)
    graph.add_node("web_data_fetcher", web_data_fetcher)
    graph.add_node("velocity_sequence", velocity_sequence)
    graph.add_node("investigator_nlm", investigator_nlm)
    graph.add_node("decision_triage", decision_triage)
    # Linear edges
    graph.add_edge("context_gatherer", "web_data_fetcher")
    graph.add_edge("web_data_fetcher", "velocity_sequence")
    graph.add_edge("velocity_sequence", "investigator_nlm")
    graph.add_edge("investigator_nlm", "decision_triage")
    # Entry point
    graph.set_entry_point("context_gatherer")
    return graph

# Cache the graph instance for reuse across requests
_GRAPH = _build_graph()


def run_graph(state: FraudState) -> FraudState:
    """Execute the graph on the provided ``FraudState``.

    Returns the final mutated state after all agents have run.
    """
    # LangGraph's ``run`` method works synchronously for regular callables
    result = _GRAPH.run(state)
    return result

